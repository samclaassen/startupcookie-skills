#!/usr/bin/env python3
"""encode_visuals.py - turn a folder of post images into TypeScript data-URL modules.

Type apps store source text only, so images ship as data URLs inside .ts files.
Each source file has a size cap, so images are split across visuals-a.ts,
visuals-b.ts, ... and re-exported from visuals.ts.

Usage:
    python3 encode_visuals.py <image_dir> <app_src_dir> [--max-file-kb 480]
                              [--max-edge 0] [--jpeg-quality 90]

- Each image becomes an export named after its file stem, sanitised to a valid
  identifier (e.g. "post-1 v2.png" -> post_1_v2).
- Export shape: { src: "data:...", file: "<original filename>", w, h }
- --max-edge 0 (default) keeps full original resolution, so the app's Download
  button gives the publishable file. Set e.g. 1600 only if a single image is
  larger than the per-file cap.
- PNGs with transparency stay PNG. Opaque PNGs larger than 300 KB are
  re-encoded as high-quality JPEG unless --keep-png is passed.
Requires Pillow.
"""
import argparse
import base64
import io
import os
import re
import sys

from PIL import Image

EXTS = {".png", ".jpg", ".jpeg", ".webp", ".gif"}


def ident(stem):
    s = re.sub(r"[^0-9A-Za-z_]", "_", stem)
    if not s or s[0].isdigit():
        s = "v_" + s
    return s


def encode(path, max_edge, quality, keep_png):
    name = os.path.basename(path)
    ext = os.path.splitext(name)[1].lower()
    im = Image.open(path)
    im.load()
    if max_edge and max(im.size) > max_edge:
        im.thumbnail((max_edge, max_edge), Image.LANCZOS)
    has_alpha = im.mode in ("RGBA", "LA") or (im.mode == "P" and "transparency" in im.info)
    buf = io.BytesIO()
    if ext in (".jpg", ".jpeg"):
        im.convert("RGB").save(buf, "JPEG", quality=quality, optimize=True, progressive=True)
        mime, out_name = "image/jpeg", name
    elif ext == ".gif":
        with open(path, "rb") as fh:
            buf.write(fh.read())
        mime, out_name = "image/gif", name
    else:
        im.save(buf, "PNG", optimize=True)
        mime, out_name = "image/png", os.path.splitext(name)[0] + ".png"
        if not has_alpha and not keep_png and buf.tell() > 300 * 1024:
            buf = io.BytesIO()
            im.convert("RGB").save(buf, "JPEG", quality=quality, optimize=True, progressive=True)
            mime, out_name = "image/jpeg", os.path.splitext(name)[0] + ".jpg"
    data = base64.b64encode(buf.getvalue()).decode("ascii")
    return {"src": f"data:{mime};base64,{data}", "file": out_name, "w": im.size[0], "h": im.size[1]}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("image_dir")
    ap.add_argument("app_src_dir")
    ap.add_argument("--max-file-kb", type=int, default=480)
    ap.add_argument("--max-edge", type=int, default=0)
    ap.add_argument("--jpeg-quality", type=int, default=90)
    ap.add_argument("--keep-png", action="store_true")
    args = ap.parse_args()

    files = sorted(f for f in os.listdir(args.image_dir) if os.path.splitext(f)[1].lower() in EXTS)
    if not files:
        sys.exit(f"no images in {args.image_dir}")

    cap = args.max_file_kb * 1024
    chunks, current, size = [], [], 0
    seen = set()
    for f in files:
        key = ident(os.path.splitext(f)[0])
        if key in seen:
            sys.exit(f"duplicate export name {key}; rename one of the files")
        seen.add(key)
        rec = encode(os.path.join(args.image_dir, f), args.max_edge, args.jpeg_quality, args.keep_png)
        line = (f'export const {key} = {{ src: "{rec["src"]}", file: "{rec["file"]}", '
                f'w: {rec["w"]}, h: {rec["h"]} }};\n')
        if len(line) > cap:
            sys.exit(f"{f} encodes to {len(line)//1024} KB, over the {args.max_file_kb} KB cap. "
                     f"Re-run with --max-edge 1600 (or lower) or split the image.")
        if current and size + len(line) > cap:
            chunks.append(current)
            current, size = [], 0
        current.append(line)
        size += len(line)
        print(f"{f} -> {key} ({rec['w']}x{rec['h']}, {len(line)//1024} KB)")
    if current:
        chunks.append(current)

    os.makedirs(args.app_src_dir, exist_ok=True)
    for old in os.listdir(args.app_src_dir):
        if re.fullmatch(r"visuals-[a-z]+\.ts", old):
            os.remove(os.path.join(args.app_src_dir, old))
    names = []
    for i, chunk in enumerate(chunks):
        suffix = ""
        n = i
        while True:
            suffix = chr(ord("a") + n % 26) + suffix
            n = n // 26 - 1
            if n < 0:
                break
        fname = f"visuals-{suffix}.ts"
        names.append(fname)
        with open(os.path.join(args.app_src_dir, fname), "w", encoding="utf-8") as fh:
            fh.write("// Generated by encode_visuals.py. Do not edit by hand.\n")
            fh.writelines(chunk)
    with open(os.path.join(args.app_src_dir, "visuals.ts"), "w", encoding="utf-8") as fh:
        fh.write("// Generated by encode_visuals.py. Re-exports every visuals-*.ts file.\n")
        for fname in names:
            fh.write(f'export * from "./{fname[:-3]}";\n')
    print(f"wrote {len(names)} file(s): {', '.join(names)} + visuals.ts")


if __name__ == "__main__":
    main()
